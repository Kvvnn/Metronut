def lerp(a, b, t):
    """Linear interpolation between two points"""
    return (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t)

def distribute_between(start, end, count):
    """Distribute points evenly between start and end"""
    if count <= 0:
        return []
    points = []
    for i in range(count):
        t = (i + 1) / (count + 1)
        points.append(lerp(start, end, t))
    return points

def distribute_along_path(anchors, station_ids):
    """
    anchors: list of (station_id, (x, y)) - known positions
    station_ids: ordered list of all station IDs on this segment
    Returns dict of {station_id: (x, y)}
    """
    result = {}
    
    # Set anchor positions
    anchor_indices = {}
    for sid, pos in anchors:
        if sid in station_ids:
            idx = station_ids.index(sid)
            anchor_indices[idx] = pos
            result[sid] = pos
    
    if not anchor_indices:
        return result
    
    sorted_anchors = sorted(anchor_indices.items())
    
    # Fill before first anchor
    if sorted_anchors[0][0] > 0:
        first_idx, first_pos = sorted_anchors[0]
        if len(sorted_anchors) > 1:
            second_idx, second_pos = sorted_anchors[1]
            dx = (second_pos[0] - first_pos[0]) / (second_idx - first_idx)
            dy = (second_pos[1] - first_pos[1]) / (second_idx - first_idx)
        else:
            dx, dy = 0, -25  # default upward
        for i in range(first_idx):
            offset = first_idx - i
            result[station_ids[i]] = (first_pos[0] - dx * offset, first_pos[1] - dy * offset)
    
    # Fill between anchors
    for a_idx in range(len(sorted_anchors) - 1):
        idx1, pos1 = sorted_anchors[a_idx]
        idx2, pos2 = sorted_anchors[a_idx + 1]
        gap = idx2 - idx1
        for i in range(idx1 + 1, idx2):
            t = (i - idx1) / gap
            result[station_ids[i]] = lerp(pos1, pos2, t)
    
    # Fill after last anchor
    if sorted_anchors[-1][0] < len(station_ids) - 1:
        last_idx, last_pos = sorted_anchors[-1]
        if len(sorted_anchors) > 1:
            prev_idx, prev_pos = sorted_anchors[-2]
            dx = (last_pos[0] - prev_pos[0]) / (last_idx - prev_idx)
            dy = (last_pos[1] - prev_pos[1]) / (last_idx - prev_idx)
        else:
            dx, dy = 0, 25
        for i in range(last_idx + 1, len(station_ids)):
            offset = i - last_idx
            result[station_ids[i]] = (last_pos[0] + dx * offset, last_pos[1] + dy * offset)
    
    return result

