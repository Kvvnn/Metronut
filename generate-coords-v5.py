# Generate coordinates
# ============================================================
coords = {}

for line_id, waypoints in line_waypoints.items():
    ordered = get_ordered_stations(line_id)
    if not ordered:
        continue
    
    n = len(ordered)
    points = interpolate_points(waypoints, n)
    
    for i, sid in enumerate(ordered):
        if i < len(points):
            coords[sid] = {'x': round(points[i][0], 1), 'y': round(points[i][1], 1)}

# Handle lines not in waypoints - use simple positioning
all_station_ids = set(s['id'] for s in metro['stations'])
missing = all_station_ids - set(coords.keys())

# For missing stations, position them near related stations
for sid in missing:
    info = station_info[sid]
    line_id = info['lineId']
    # Try to find a nearby station on the same line that has coords
    same_line = [s for s in metro['stations'] if s['lineId'] == line_id and s['id'] in coords]
    if same_line:
        # Position near the last station of the same line
        ref = same_line[-1]
        ref_coord = coords[ref['id']]
        coords[sid] = {'x': ref_coord['x'] + 20, 'y': ref_coord['y'] + 20}
    else:
        # Default position
        coords[sid] = {'x': 950, 'y': 810}

# Write output
output = {'stations': coords}
with open('client/src/data/mapCoords.json', 'w', encoding='utf-8') as f:
    json.dump(output, f, separators=(',', ':'))

