def get_ordered_stations(line_id):
    """Get stations in order along the line using edge traversal"""
    edges = line_edges.get(line_id, [])
    if not edges:
        return line_stations.get(line_id, [])
    
    adj = {}
    for src, tgt in edges:
        if src not in adj: adj[src] = []
        if tgt not in adj: adj[tgt] = []
        adj[src].append(tgt)
        adj[tgt].append(src)
    
    # Find endpoint (node with degree 1) or just start from first
    stations_in_line = set(line_stations.get(line_id, []))
    endpoints = [s for s in stations_in_line if s in adj and len([n for n in adj[s] if n in stations_in_line]) == 1]
    
    if endpoints:
        start = endpoints[0]
    else:
        start = line_stations[line_id][0]
    
    ordered = [start]
    visited = {start}
    current = start
    while True:
        neighbors = [n for n in adj.get(current, []) if n not in visited and n in stations_in_line]
        if not neighbors:
            break
        next_node = neighbors[0]
        ordered.append(next_node)
        visited.add(next_node)
        current = next_node
    
    return ordered

def interpolate_points(points, n):
    """Interpolate n points along a polyline defined by points"""
    if n <= 0:
        return []
    if n == 1:
        return [points[0]]
    
    # Calculate total length
    lengths = [0]
    for i in range(1, len(points)):
        dx = points[i][0] - points[i-1][0]
        dy = points[i][1] - points[i-1][1]
        lengths.append(lengths[-1] + math.sqrt(dx*dx + dy*dy))
    
    total = lengths[-1]
    if total == 0:
        return [points[0]] * n
    
    result = []
    for i in range(n):
        t = i / (n - 1) if n > 1 else 0
        target_len = t * total
        
        # Find segment
        for j in range(1, len(lengths)):
            if lengths[j] >= target_len:
                seg_start = lengths[j-1]
                seg_end = lengths[j]
                seg_len = seg_end - seg_start
                if seg_len == 0:
                    frac = 0
                else:
                    frac = (target_len - seg_start) / seg_len
                x = points[j-1][0] + frac * (points[j][0] - points[j-1][0])
                y = points[j-1][1] + frac * (points[j][1] - points[j-1][1])
                result.append((x, y))
                break
        else:
            result.append(points[-1])
    
    return result

