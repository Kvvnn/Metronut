function normalizeLineId(lineId: string) {
  return LINE_ID_ALIASES[lineId] ?? lineId;
}

function makeKey(stationName: string, fromLineId: string, toLineId: string) {
  return `${stationName}|${normalizeLineId(fromLineId)}|${normalizeLineId(toLineId)}`;
}

